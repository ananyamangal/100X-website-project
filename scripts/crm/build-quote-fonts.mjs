// Regenerates lib/crm/quotes/fonts.generated.ts (base64 WOFF) from unpacked @fontsource packages.
// The quotation PDF embeds these so it needs no font files on disk at runtime (Vercel bundling).
//
//   npm pack @fontsource/noto-sans@5.3.0 @fontsource/noto-sans-devanagari@5.3.0   (in a temp dir)
//   tar -xzf each into <dir>/fontsource-noto-sans-5.3.0/ and <dir>/fontsource-noto-sans-devanagari-5.3.0/
//   node scripts/crm/build-quote-fonts.mjs <dir>
//
// Fonts: Noto Sans + Noto Sans Devanagari, SIL Open Font License 1.1 (lib/crm/quotes/fonts/OFL.txt).
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

const dir = process.argv[2]
if (!dir) throw new Error("usage: node scripts/crm/build-quote-fonts.mjs <dir with unpacked fontsource packages>")
const SANS = path.join(dir, "fontsource-noto-sans-5.3.0", "package")
const DEVA = path.join(dir, "fontsource-noto-sans-devanagari-5.3.0", "package")
const files = {
  latin400: [SANS, "noto-sans-latin-400-normal.woff"],
  latin700: [SANS, "noto-sans-latin-700-normal.woff"],
  latinExt400: [SANS, "noto-sans-latin-ext-400-normal.woff"],
  latinExt700: [SANS, "noto-sans-latin-ext-700-normal.woff"],
  deva400: [DEVA, "noto-sans-devanagari-devanagari-400-normal.woff"],
  deva700: [DEVA, "noto-sans-devanagari-devanagari-700-normal.woff"],
}
let out = `// GENERATED by scripts/crm/build-quote-fonts.mjs — do not edit.
// Source: @fontsource/noto-sans@5.3.0, @fontsource/noto-sans-devanagari@5.3.0 (WOFF subsets; WOFF2 breaks fontkit subsetting of composite glyphs).
// License: SIL Open Font License 1.1, see lib/crm/quotes/fonts/OFL.txt.
/* eslint-disable */
`
for (const [name, [d, f]] of Object.entries(files)) {
  const b64 = readFileSync(path.join(d, "files", f)).toString("base64")
  out += `export const ${name} = "${b64}"\n`
}
writeFileSync("lib/crm/quotes/fonts.generated.ts", out)
const lic = (label, d) => `==== ${label} ====\n\n${readFileSync(path.join(d, "LICENSE"), "utf8").trim()}\n`
const licenses = [lic("Noto Sans (@fontsource/noto-sans@5.3.0)", SANS), lic("Noto Sans Devanagari (@fontsource/noto-sans-devanagari@5.3.0)", DEVA)]
writeFileSync("lib/crm/quotes/fonts/OFL.txt", licenses.join("\n"))
console.log("wrote lib/crm/quotes/fonts.generated.ts", out.length, "bytes")
